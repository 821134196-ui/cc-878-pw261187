import dgram from 'node:dgram';
import { ORIGINS } from './config.js';

/**
 * The control plane for the in-process authoritative demo DNS server.
 * Changing this object changes future DNS answers; it does not mutate any
 * proxy connection pool directly.
 */
export class DemoDnsRegistry {
  constructor(config) {
    this.config = config;
    this.activeColor = 'blue';
    this.faultMode = 'none';
    this.serial = 1;
  }

  update({ activeColor, faultMode } = {}) {
    let changed = false;
    if (activeColor && activeColor !== this.activeColor && ORIGINS[activeColor]) {
      this.activeColor = activeColor;
      changed = true;
    }
    if (faultMode !== undefined && faultMode !== this.faultMode) {
      this.faultMode = faultMode;
      changed = true;
    }
    if (changed) this.serial += 1;
    return this.describe();
  }

  describe() {
    return {
      activeColor: this.activeColor,
      faultMode: this.faultMode,
      serial: this.serial,
      srv: this.srvRecords(),
    };
  }

  srvRecords() {
    const records = [];

    if (this.faultMode === 'conn-refused') {
      records.push({
        target: this.config.deadTarget,
        port: this.config.deadPort,
        priority: 1,
        weight: 10,
        kind: 'fault',
        fault: 'ECONNREFUSED',
        label: '故障地址：端口无监听',
      });
    }

    if (this.faultMode === 'header-timeout') {
      records.push({
        target: this.config.tarpitTarget,
        port: this.config.tarpitPort,
        priority: 1,
        weight: 10,
        kind: 'fault',
        fault: 'HEADER_TIMEOUT',
        label: '故障地址：接受连接但不返回响应头',
      });
    }

    const active = ORIGINS[this.activeColor];
    records.push({
      target: `${this.activeColor}.origin.demo.local`,
      port: active.port,
      priority: 10,
      weight: 10,
      kind: 'origin',
      color: this.activeColor,
      label: active.label,
    });

    if (this.faultMode === 'dns-timeout') {
      records.push({
        target: this.config.ghostTarget,
        port: this.config.deadPort,
        priority: 20,
        weight: 0,
        kind: 'unresolved',
        fault: 'DNS_TIMEOUT',
        label: '部分解析超时：A 记录查询被演示 DNS 丢弃',
      });
    }

    return records;
  }

  aRecord(name) {
    if (name === this.config.ghostTarget) return null;
    if (name.endsWith('.origin.demo.local')) return '127.0.0.1';
    return null;
  }
}

function parseQuestion(buf) {
  if (buf.length < 17) return null;
  let offset = 12;
  const labels = [];

  while (offset < buf.length) {
    const length = buf[offset];
    if (length === 0) {
      offset += 1;
      break;
    }
    // Questions generated by c-ares use an uncompressed qname.
    labels.push(buf.subarray(offset + 1, offset + 1 + length).toString('ascii'));
    offset += 1 + length;
  }

  if (offset + 4 > buf.length) return null;
  const typeNumber = buf.readUInt16BE(offset);
  const qclass = buf.readUInt16BE(offset + 2);
  const type = typeNumber === 1 ? 'A' : typeNumber === 33 ? 'SRV' : typeNumber;
  return { name: labels.join('.'), type, qclass, questionEnd: offset + 4 };
}

function encodeName(name) {
  const parts = name.split('.').filter(Boolean);
  const chunks = [];
  for (const part of parts) {
    const label = Buffer.from(part, 'ascii');
    chunks.push(Buffer.from([label.length]), label);
  }
  chunks.push(Buffer.from([0]));
  return Buffer.concat(chunks);
}

function makeAnswer(type, rdata) {
  const fixed = Buffer.alloc(10);
  fixed.writeUInt16BE(type, 0);
  fixed.writeUInt16BE(1, 2); // class IN
  fixed.writeUInt32BE(0, 4); // TTL 0: every periodic refresh asks again
  fixed.writeUInt16BE(rdata.length, 8);
  // 0xc00c is a compression pointer to the question's qname.
  return Buffer.concat([Buffer.from([0xc0, 0x0c]), fixed, rdata]);
}

function makeSrvRdata(record) {
  const prefix = Buffer.alloc(6);
  prefix.writeUInt16BE(record.priority ?? 10, 0);
  prefix.writeUInt16BE(record.weight ?? 10, 2);
  prefix.writeUInt16BE(record.port, 4);
  return Buffer.concat([prefix, encodeName(record.target)]);
}

function buildResponse(query, question, answers, rcode = 0) {
  const header = Buffer.alloc(12);
  query.copy(header, 0, 0, 2); // transaction ID
  header.writeUInt16BE(0x8180 | rcode, 2); // QR, AA, RD, RA; rcode is in low nibble
  header.writeUInt16BE(1, 4);
  header.writeUInt16BE(answers.length, 6);
  const questionBuffer = query.subarray(12, question.questionEnd);
  return Buffer.concat([header, questionBuffer, ...answers]);
}

export function startDemoDnsServer({ config, registry, state }) {
  const socket = dgram.createSocket({ type: 'udp4', reuseAddr: true });

  socket.on('message', (message, remote) => {
    let question;
    try {
      question = parseQuestion(message);
      if (!question) return;

      if (question.type === 'SRV' && question.name === config.dnsName) {
        const records = registry.srvRecords();
        const answers = records.map((record) => makeAnswer(33, makeSrvRdata(record)));
        const response = buildResponse(message, question, answers);
        socket.send(response, remote.port, remote.address);
        state.dns.lastServerQuery = {
          at: Date.now(),
          type: 'SRV',
          name: question.name,
          count: records.length,
        };
        return;
      }

      if (question.type === 'A') {
        const ip = registry.aRecord(question.name);
        if (!ip) {
          state.stats.dnsDroppedQueries = (state.stats.dnsDroppedQueries || 0) + 1;
          state.log({
            layer: 'dns',
            kind: 'dns_query_dropped',
            severity: 'warning',
            title: '演示 DNS 丢弃 A 查询',
            detail: `${question.name} 不会收到响应；解析器将其记为 DNS_TIMEOUT，而不是连接失败。`,
            meta: { name: question.name, remote },
          });
          return;
        }

        const parts = ip.split('.').map(Number);
        const response = buildResponse(message, question, [makeAnswer(1, Buffer.from(parts))]);
        socket.send(response, remote.port, remote.address);
        state.dns.lastServerQuery = { at: Date.now(), type: 'A', name: question.name, ip };
        return;
      }

      const response = buildResponse(message, question, [], 3); // NXDOMAIN
      socket.send(response, remote.port, remote.address);
    } catch (error) {
      state.log({
        layer: 'dns',
        kind: 'dns_server_error',
        severity: 'critical',
        title: '演示 DNS 服务端编码响应失败',
        detail: error.message,
      });
    }
  });

  socket.on('error', (error) => {
    state.log({
      layer: 'dns',
      kind: 'dns_socket_error',
      severity: 'critical',
      title: 'DNS UDP socket 错误',
      detail: error.message,
    });
  });

  return new Promise((resolve, reject) => {
    socket.once('error', reject);
    socket.bind(config.dnsPort, config.dnsHost, () => {
      state.log({
        layer: 'dns',
        kind: 'dns_listening',
        severity: 'success',
        title: '内置演示 DNS 已启动',
        detail: `udp://${config.dnsHost}:${config.dnsPort} · SRV ${config.dnsName}`,
      });
      resolve({
        port: config.dnsPort,
        close: () => new Promise((done) => socket.close(done)),
      });
    });
  });
}
